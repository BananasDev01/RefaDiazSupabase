RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    q public.quotation%ROWTYPE;
    cv public.client_vehicle%ROWTYPE;
    c public.client%ROWTYPE;
    v public.vehicle%ROWTYPE;
    cm public.car_model%ROWTYPE;
    b public.brand%ROWTYPE;
    au public."user"%ROWTYPE;
    ap public.person%ROWTYPE;
    expected_version_value INTEGER;
    attended_id TEXT;
BEGIN
    PERFORM public.assert_staff_actor_v1(p_actor_user_id);
    expected_version_value := (p_payload->>'expected_version')::INTEGER;
    SELECT * INTO q FROM public.quotation
    WHERE external_id = (p_payload->>'external_id')::UUID FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'QUOTATION_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
    IF q.version <> expected_version_value THEN
        RAISE EXCEPTION 'QUOTATION_VERSION_CONFLICT current=% expected=%', q.version, expected_version_value
            USING ERRCODE = 'P0001';
    END IF;
    IF q.status IN ('ACCEPTED', 'CANCELLED') THEN
        RAISE EXCEPTION 'QUOTATION_INVALID_STATE_%', q.status USING ERRCODE = '55000';
    END IF;
    SELECT * INTO cv FROM public.client_vehicle
    WHERE id = (p_payload->>'client_vehicle_id')::BIGINT AND active = true;
    IF NOT FOUND THEN RAISE EXCEPTION 'CLIENT_VEHICLE_NOT_FOUND' USING ERRCODE = '23503'; END IF;
    SELECT * INTO c FROM public.client WHERE id = cv.client_id AND active = true;
    SELECT * INTO v FROM public.vehicle WHERE id = cv.vehicle_id AND active = true;
    IF v.car_model_id IS NOT NULL THEN
        SELECT * INTO cm FROM public.car_model WHERE id = v.car_model_id;
        IF cm.brand_id IS NOT NULL THEN SELECT * INTO b FROM public.brand WHERE id = cm.brand_id; END IF;
    END IF;
    attended_id := nullif(btrim(p_payload->>'attended_by_user_id'), '');
    IF attended_id IS NOT NULL THEN
        SELECT * INTO au FROM public."user" WHERE id = attended_id AND active = true;
        IF NOT FOUND THEN RAISE EXCEPTION 'QUOTATION_ATTENDED_BY_NOT_FOUND' USING ERRCODE = '23503'; END IF;
        SELECT * INTO ap FROM public.person WHERE id = au.person_id;
    END IF;
    UPDATE public.quotation SET
        quotation_date = coalesce((p_payload->>'quotation_date')::DATE, CURRENT_DATE),
        valid_until = (p_payload->>'valid_until')::DATE,
        client_vehicle_id = cv.id, client_id = cv.client_id, vehicle_id = cv.vehicle_id,
        attended_by_user_id = attended_id, notes = nullif(btrim(p_payload->>'notes'), ''),
        client_snapshot = jsonb_build_object('id', c.id, 'external_id', c.external_id,
            'client_name', c.client_name, 'phone_number', c.phone_number,
            'phone_normalized', c.phone_normalized),
        vehicle_snapshot = jsonb_build_object('id', v.id, 'external_id', v.external_id,
            'brand_id', b.id, 'brand_name', b.name, 'car_model_id', cm.id,
            'car_model_name', cm.name, 'model_year', v.model_year,
            'version', v.version, 'color', v.color, 'plate', v.plate),
        attended_by_snapshot = CASE WHEN attended_id IS NULL THEN NULL ELSE jsonb_build_object(
            'user_id', au.id, 'person_id', ap.id,
            'name', concat_ws(' ', ap.name, ap.last_name)) END,
        legal_text_snapshot = coalesce(p_payload->'legal_text_snapshot', '{}'::JSONB),
        updated_by_user_id = p_actor_user_id
    WHERE id = q.id;
    PERFORM public.replace_quotation_options_v1(q.id, p_payload->'options');
    RETURN public.quotation_public_json_v1(q.id);
END;
$$;

CREATE OR REPLACE FUNCTION public.transition_quotation_v1(
    p_external_id UUID, p_expected_version INTEGER, p_action TEXT,
    p_valid_until DATE, p_actor_user_id TEXT
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE q public.quotation%ROWTYPE; action_value TEXT := upper(p_action);
BEGIN
    PERFORM public.assert_staff_actor_v1(p_actor_user_id);
    SELECT * INTO q FROM public.quotation WHERE external_id = p_external_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'QUOTATION_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
    IF q.version <> p_expected_version THEN
        IF (action_value = 'SEND' AND q.status = 'SENT' AND q.version = p_expected_version + 1)
           OR (action_value = 'CANCEL' AND q.status = 'CANCELLED' AND q.version = p_expected_version + 1)
           OR (action_value = 'REACTIVATE' AND q.status = 'DRAFT'
               AND q.valid_until = p_valid_until AND q.version = p_expected_version + 1) THEN
            RETURN public.quotation_public_json_v1(q.id) || jsonb_build_object('idempotent_replay', true);
        END IF;
        RAISE EXCEPTION 'QUOTATION_VERSION_CONFLICT current=% expected=%', q.version, p_expected_version
            USING ERRCODE = 'P0001';
    END IF;
    IF action_value = 'SEND' THEN
        IF q.status <> 'DRAFT' OR (q.valid_until IS NOT NULL AND q.valid_until < CURRENT_DATE) THEN
            RAISE EXCEPTION 'QUOTATION_INVALID_STATE_%', public.quotation_effective_status_v1(q.status, q.valid_until)
                USING ERRCODE = '55000';
        END IF;
        UPDATE public.quotation SET status = 'SENT', updated_by_user_id = p_actor_user_id WHERE id = q.id;
    ELSIF action_value = 'CANCEL' THEN
        IF q.status = 'ACCEPTED' THEN
            RAISE EXCEPTION 'QUOTATION_INVALID_STATE_ACCEPTED' USING ERRCODE = '55000';
        END IF;
        UPDATE public.quotation SET status = 'CANCELLED', cancelled_at = now(),
            cancelled_by_user_id = p_actor_user_id, updated_by_user_id = p_actor_user_id WHERE id = q.id;
    ELSIF action_value = 'REACTIVATE' THEN
        IF public.quotation_effective_status_v1(q.status, q.valid_until) <> 'EXPIRED'
           OR p_valid_until IS NULL OR p_valid_until < CURRENT_DATE
           OR p_valid_until < q.quotation_date THEN
            RAISE EXCEPTION 'QUOTATION_REACTIVATION_INVALID' USING ERRCODE = '55000';
        END IF;
        UPDATE public.quotation SET status = 'DRAFT', valid_until = p_valid_until,
            updated_by_user_id = p_actor_user_id WHERE id = q.id;
    ELSE
        RAISE EXCEPTION 'QUOTATION_ACTION_INVALID' USING ERRCODE = '22023';
    END IF;
    RETURN public.quotation_public_json_v1(q.id) || jsonb_build_object('idempotent_replay', false);
END;
$$;

CREATE OR REPLACE FUNCTION public.get_quotation_v1(
    p_quotation_id BIGINT DEFAULT NULL, p_external_id UUID DEFAULT NULL
)
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE id_value BIGINT;
BEGIN
    SELECT id INTO id_value FROM public.quotation
    WHERE (p_quotation_id IS NOT NULL AND id = p_quotation_id)
       OR (p_external_id IS NOT NULL AND external_id = p_external_id)
    ORDER BY CASE WHEN external_id = p_external_id THEN 0 ELSE 1 END LIMIT 1;
    IF id_value IS NULL THEN RAISE EXCEPTION 'QUOTATION_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
    RETURN public.quotation_public_json_v1(id_value);
END;
$$;

CREATE OR REPLACE FUNCTION public.search_quotations_v1(
    p_folio TEXT DEFAULT NULL, p_client_id INTEGER DEFAULT NULL,
    p_status TEXT DEFAULT NULL, p_date_from DATE DEFAULT NULL, p_date_to DATE DEFAULT NULL,
    p_phone TEXT DEFAULT NULL, p_limit INTEGER DEFAULT 50, p_offset INTEGER DEFAULT 0
)
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    result JSONB; normalized_phone TEXT := public.normalize_phone_v1(p_phone);
    safe_limit INTEGER := greatest(1, least(coalesce(p_limit, 50), 100));
    safe_offset INTEGER := greatest(coalesce(p_offset, 0), 0);
BEGIN
    WITH matching AS (
        SELECT q.id FROM public.quotation q
        JOIN public.client c ON c.id = q.client_id
        WHERE (nullif(btrim(p_folio), '') IS NULL
            OR concat_ws('-', q.folio_series, q.folio_number::TEXT) ILIKE '%' || btrim(p_folio) || '%'
            OR q.provisional_reference ILIKE '%' || btrim(p_folio) || '%')
          AND (p_client_id IS NULL OR q.client_id = p_client_id)
          AND (p_status IS NULL OR public.quotation_effective_status_v1(q.status, q.valid_until) = upper(p_status))
          AND (p_date_from IS NULL OR q.quotation_date >= p_date_from)
          AND (p_date_to IS NULL OR q.quotation_date <= p_date_to)
          AND (nullif(btrim(p_phone), '') IS NULL
            OR (normalized_phone IS NOT NULL AND c.phone_normalized = normalized_phone))
    ), page AS (
        SELECT q.id FROM matching m JOIN public.quotation q ON q.id = m.id
        ORDER BY q.created_at DESC, q.id DESC LIMIT safe_limit OFFSET safe_offset
    )
    SELECT jsonb_build_object(
        'data', coalesce((SELECT jsonb_agg(public.quotation_public_json_v1(id)) FROM page), '[]'::JSONB),
        'pagination', jsonb_build_object('limit', safe_limit, 'offset', safe_offset,
            'total', (SELECT count(*) FROM matching))
    ) INTO result;
    RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION public.duplicate_quotation_v1(
    p_source_external_id UUID, p_new_external_id UUID, p_provisional_reference TEXT,
    p_quotation_date DATE, p_valid_until DATE, p_actor_user_id TEXT
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE source public.quotation%ROWTYPE; existing public.quotation%ROWTYPE; payload JSONB;
BEGIN
    PERFORM public.assert_staff_actor_v1(p_actor_user_id);
    SELECT * INTO source FROM public.quotation WHERE external_id = p_source_external_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'QUOTATION_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
    SELECT * INTO existing FROM public.quotation WHERE external_id = p_new_external_id;
    IF FOUND THEN
        IF existing.duplicated_from_quotation_id <> source.id THEN
            RAISE EXCEPTION 'QUOTATION_EXTERNAL_ID_CONFLICT' USING ERRCODE = '23505';
        END IF;
        RETURN public.quotation_public_json_v1(existing.id) || jsonb_build_object('idempotent_replay', true);
    END IF;
    SELECT jsonb_build_object(
        'external_id', p_new_external_id, 'provisional_reference', p_provisional_reference,
        'quotation_date', coalesce(p_quotation_date, CURRENT_DATE), 'valid_until', p_valid_until,
        'client_vehicle_id', source.client_vehicle_id,
        'attended_by_user_id', source.attended_by_user_id, 'notes', source.notes,
        'legal_text_snapshot', source.legal_text_snapshot,
        'options', (SELECT jsonb_agg(jsonb_build_object(
            'external_id', gen_random_uuid(), 'name', o.name, 'description', o.description,
            'tax_amount', o.tax_amount, 'warranty_months', o.warranty_months,
            'items', (SELECT jsonb_agg(jsonb_build_object(
                'external_id', gen_random_uuid(), 'product_id', i.product_id,
                'description_snapshot', i.description_snapshot, 'quantity', i.quantity,
                'unit_price', i.unit_price, 'warranty_months', i.warranty_months
            ) ORDER BY i.display_order) FROM public.quotation_item i WHERE i.quotation_option_id = o.id)
        ) ORDER BY o.display_order) FROM public.quotation_option o WHERE o.quotation_id = source.id)
    ) INTO payload;
    PERFORM public.create_quotation_v1(payload, p_actor_user_id);
    UPDATE public.quotation SET duplicated_from_quotation_id = source.id,
        updated_by_user_id = p_actor_user_id
    WHERE external_id = p_new_external_id RETURNING * INTO existing;
    RETURN public.quotation_public_json_v1(existing.id) || jsonb_build_object('idempotent_replay', false);
END;
$$;

CREATE OR REPLACE FUNCTION public.convert_quotation_to_service_v1(
    p_quotation_external_id UUID, p_option_external_id UUID,
    p_expected_version INTEGER, p_service_external_id UUID,
    p_service_provisional_reference TEXT, p_service_date DATE,
    p_actor_user_id TEXT
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    q public.quotation%ROWTYPE; o public.quotation_option%ROWTYPE;
    existing_service public.service%ROWTYPE; service_result JSONB; service_id_value BIGINT;
    description_value TEXT;
BEGIN
    PERFORM public.assert_staff_actor_v1(p_actor_user_id);
    SELECT * INTO q FROM public.quotation WHERE external_id = p_quotation_external_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'QUOTATION_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
    IF q.converted_service_id IS NOT NULL THEN
        SELECT * INTO existing_service FROM public.service WHERE id = q.converted_service_id;
        IF existing_service.external_id IS DISTINCT FROM p_service_external_id
           OR q.accepted_option_id IS DISTINCT FROM
                (SELECT id FROM public.quotation_option WHERE external_id = p_option_external_id) THEN
            RAISE EXCEPTION 'QUOTATION_ALREADY_CONVERTED' USING ERRCODE = '23505';
        END IF;
        RETURN jsonb_build_object('quotation', public.quotation_public_json_v1(q.id),
            'service', public.service_public_json_v1(existing_service.id), 'idempotent_replay', true);
    END IF;
    IF q.version <> p_expected_version THEN
        RAISE EXCEPTION 'QUOTATION_VERSION_CONFLICT current=% expected=%', q.version, p_expected_version
            USING ERRCODE = 'P0001';
    END IF;
    IF public.quotation_effective_status_v1(q.status, q.valid_until) = 'EXPIRED' THEN
        RAISE EXCEPTION 'QUOTATION_EXPIRED' USING ERRCODE = '55000';
    END IF;
    IF q.status NOT IN ('DRAFT', 'SENT') THEN
        RAISE EXCEPTION 'QUOTATION_INVALID_STATE_%', q.status USING ERRCODE = '55000';
    END IF;
    SELECT * INTO existing_service FROM public.service
    WHERE external_id = p_service_external_id;
    IF FOUND THEN
        RAISE EXCEPTION 'QUOTATION_SERVICE_EXTERNAL_ID_CONFLICT'
            USING ERRCODE = '23505';
    END IF;
    SELECT * INTO o FROM public.quotation_option
    WHERE quotation_id = q.id AND external_id = p_option_external_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'QUOTATION_OPTION_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
    SELECT string_agg(description_snapshot, E'\n' ORDER BY display_order)
    INTO description_value FROM public.quotation_item WHERE quotation_option_id = o.id;
    service_result := public.create_service_v1(jsonb_build_object(
        'external_id', p_service_external_id,
        'provisional_reference', coalesce(nullif(btrim(p_service_provisional_reference), ''),
            'PEND-SER-' || upper(left(p_service_external_id::TEXT, 8))),
        'client_vehicle_id', q.client_vehicle_id,
        'service_date', coalesce(p_service_date, CURRENT_DATE),
        'work_manager_user_id', q.attended_by_user_id,
        'authorized_work_description', description_value,
        'subtotal', o.subtotal, 'tax_amount', o.tax_amount,
        'warranty_months', o.warranty_months,
        'legal_text_snapshot', q.legal_text_snapshot
    ), p_actor_user_id);
    service_id_value := (service_result->>'id')::BIGINT;
    UPDATE public.service SET source_quotation_id = q.id,
        source_quotation_option_id = o.id,
        client_snapshot = q.client_snapshot, vehicle_snapshot = q.vehicle_snapshot,
        work_manager_snapshot = q.attended_by_snapshot,
        legal_text_snapshot = q.legal_text_snapshot,
        updated_by_user_id = p_actor_user_id
    WHERE id = service_id_value;
    INSERT INTO public.service_item (
        external_id, service_id, source_quotation_item_id, product_id,
        product_name_snapshot, description_snapshot, quantity, unit_price,
        line_total, warranty_months, display_order
    ) SELECT gen_random_uuid(), service_id_value, i.id, i.product_id,
        i.product_name_snapshot, i.description_snapshot, i.quantity, i.unit_price,
        i.line_total, i.warranty_months, i.display_order
    FROM public.quotation_item i WHERE i.quotation_option_id = o.id
    ORDER BY i.display_order;
    UPDATE public.quotation SET status = 'ACCEPTED', accepted_option_id = o.id,
        accepted_subtotal = o.subtotal, accepted_tax_amount = o.tax_amount,
        accepted_total = o.total, converted_service_id = service_id_value,
        accepted_at = now(), accepted_by_user_id = p_actor_user_id,
        updated_by_user_id = p_actor_user_id
    WHERE id = q.id;
    RETURN jsonb_build_object('quotation', public.quotation_public_json_v1(q.id),
        'service', public.service_public_json_v1(service_id_value), 'idempotent_replay', false);
END;
$$;

