CREATE OR REPLACE FUNCTION public.touch_quotation_version_v1()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.external_id IS DISTINCT FROM OLD.external_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.created_by_user_id IS DISTINCT FROM OLD.created_by_user_id THEN
        RAISE EXCEPTION 'Immutable quotation identity fields cannot be changed'
            USING ERRCODE = '22000';
    END IF;
    IF NEW.version IS DISTINCT FROM OLD.version THEN
        RAISE EXCEPTION 'quotation.version is managed by the database'
            USING ERRCODE = '22000';
    END IF;
    NEW.version := OLD.version + 1;
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER quotation_touch_version
BEFORE UPDATE ON public.quotation
FOR EACH ROW EXECUTE FUNCTION public.touch_quotation_version_v1();

CREATE OR REPLACE FUNCTION public.quotation_effective_status_v1(
    p_status TEXT, p_valid_until DATE
)
RETURNS TEXT LANGUAGE sql STABLE SET search_path = '' AS $$
    SELECT CASE
        WHEN p_status IN ('DRAFT', 'SENT')
             AND p_valid_until IS NOT NULL AND p_valid_until < CURRENT_DATE
            THEN 'EXPIRED'
        ELSE p_status
    END
$$;

CREATE OR REPLACE FUNCTION public.quotation_public_json_v1(p_quotation_id BIGINT)
RETURNS JSONB LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT to_jsonb(q)
        || jsonb_build_object(
            'status', public.quotation_effective_status_v1(q.status, q.valid_until),
            'options', coalesce((
                SELECT jsonb_agg(
                    to_jsonb(o) || jsonb_build_object(
                        'items', coalesce((
                            SELECT jsonb_agg(to_jsonb(i) ORDER BY i.display_order, i.id)
                            FROM public.quotation_item i
                            WHERE i.quotation_option_id = o.id
                        ), '[]'::JSONB)
                    ) ORDER BY o.display_order, o.id
                )
                FROM public.quotation_option o WHERE o.quotation_id = q.id
            ), '[]'::JSONB)
        )
    FROM public.quotation q WHERE q.id = p_quotation_id
$$;

CREATE OR REPLACE FUNCTION public.service_public_json_v1(p_service_id BIGINT)
RETURNS JSONB LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT to_jsonb(s) || jsonb_build_object(
        'reported_failures', coalesce((
            SELECT jsonb_agg(
                to_jsonb(f) - 'service_id' - 'created_by_user_id'
                ORDER BY f.display_order_snapshot, f.id
            ) FROM public.service_reported_failure f WHERE f.service_id = s.id
        ), '[]'::JSONB),
        'items', coalesce((
            SELECT jsonb_agg(to_jsonb(i) ORDER BY i.display_order, i.id)
            FROM public.service_item i WHERE i.service_id = s.id
        ), '[]'::JSONB)
    )
    FROM public.service s WHERE s.id = p_service_id
$$;

CREATE OR REPLACE FUNCTION public.replace_quotation_options_v1(
    p_quotation_id BIGINT, p_options JSONB
)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    option_payload JSONB;
    item_payload JSONB;
    option_id_value BIGINT;
    option_external_id UUID;
    item_external_id UUID;
    product_id_value INTEGER;
    product_name_value TEXT;
    description_value TEXT;
    quantity_value NUMERIC(12, 3);
    price_value NUMERIC(12, 2);
    line_total_value NUMERIC(12, 2);
    subtotal_value NUMERIC(12, 2);
    tax_value NUMERIC(12, 2);
    option_order SMALLINT := 0;
    item_order SMALLINT;
BEGIN
    IF p_options IS NULL OR jsonb_typeof(p_options) <> 'array'
       OR jsonb_array_length(p_options) = 0 THEN
        RAISE EXCEPTION 'QUOTATION_OPTIONS_REQUIRED' USING ERRCODE = '23502';
    END IF;

    DELETE FROM public.quotation_option WHERE quotation_id = p_quotation_id;

    FOR option_payload IN SELECT value FROM jsonb_array_elements(p_options) LOOP
        option_order := option_order + 1;
        BEGIN
            option_external_id := (option_payload->>'external_id')::UUID;
        EXCEPTION WHEN OTHERS THEN
            RAISE EXCEPTION 'QUOTATION_OPTION_EXTERNAL_ID_INVALID' USING ERRCODE = '22023';
        END;
        IF nullif(btrim(option_payload->>'name'), '') IS NULL THEN
            RAISE EXCEPTION 'QUOTATION_OPTION_NAME_REQUIRED' USING ERRCODE = '23502';
        END IF;
        IF NOT option_payload ? 'tax_amount' OR option_payload->>'tax_amount' IS NULL THEN
            RAISE EXCEPTION 'QUOTATION_OPTION_TAX_AMOUNT_REQUIRED' USING ERRCODE = '23502';
        END IF;
        IF jsonb_typeof(option_payload->'items') <> 'array'
           OR jsonb_array_length(option_payload->'items') = 0 THEN
            RAISE EXCEPTION 'QUOTATION_ITEMS_REQUIRED' USING ERRCODE = '23502';
        END IF;

        tax_value := (option_payload->>'tax_amount')::NUMERIC(12, 2);
        IF tax_value < 0 THEN
            RAISE EXCEPTION 'QUOTATION_OPTION_TAX_AMOUNT_INVALID' USING ERRCODE = '22023';
        END IF;
        INSERT INTO public.quotation_option (
            external_id, quotation_id, name, description, display_order,
            subtotal, tax_amount, total, warranty_months
        ) VALUES (
            option_external_id, p_quotation_id, btrim(option_payload->>'name'),
            nullif(btrim(option_payload->>'description'), ''), option_order,
            0, tax_value, tax_value,
            CASE WHEN option_payload->>'warranty_months' IS NULL THEN NULL
                ELSE (option_payload->>'warranty_months')::SMALLINT END
        ) RETURNING id INTO option_id_value;

        subtotal_value := 0;
        item_order := 0;
        FOR item_payload IN SELECT value FROM jsonb_array_elements(option_payload->'items') LOOP
            item_order := item_order + 1;
            BEGIN
                item_external_id := (item_payload->>'external_id')::UUID;
            EXCEPTION WHEN OTHERS THEN
                RAISE EXCEPTION 'QUOTATION_ITEM_EXTERNAL_ID_INVALID' USING ERRCODE = '22023';
            END;
            product_id_value := CASE WHEN item_payload->>'product_id' IS NULL THEN NULL
                ELSE (item_payload->>'product_id')::INTEGER END;
            product_name_value := NULL;
            IF product_id_value IS NOT NULL THEN
                SELECT name INTO product_name_value FROM public.product
                WHERE id = product_id_value AND active = true;
                IF NOT FOUND THEN
                    RAISE EXCEPTION 'QUOTATION_PRODUCT_NOT_FOUND' USING ERRCODE = '23503';
                END IF;
            END IF;
            description_value := coalesce(
                nullif(btrim(item_payload->>'description_snapshot'), ''),
                nullif(btrim(item_payload->>'description'), ''),
                nullif(btrim(product_name_value), '')
            );
            IF description_value IS NULL THEN
                RAISE EXCEPTION 'QUOTATION_ITEM_DESCRIPTION_REQUIRED' USING ERRCODE = '23502';
            END IF;
            quantity_value := coalesce((item_payload->>'quantity')::NUMERIC(12, 3), 1);
            price_value := (item_payload->>'unit_price')::NUMERIC(12, 2);
            IF quantity_value <= 0 OR price_value < 0 THEN
                RAISE EXCEPTION 'QUOTATION_ITEM_AMOUNT_INVALID' USING ERRCODE = '22023';
            END IF;
            line_total_value := round(quantity_value * price_value, 2);
            INSERT INTO public.quotation_item (
                external_id, quotation_option_id, product_id, product_name_snapshot,
                description_snapshot, quantity, unit_price, line_total,
                warranty_months, display_order
            ) VALUES (
                item_external_id, option_id_value, product_id_value, product_name_value,
                description_value, quantity_value, price_value, line_total_value,
                CASE WHEN item_payload->>'warranty_months' IS NULL THEN NULL
                    ELSE (item_payload->>'warranty_months')::SMALLINT END,
                item_order
            );
            subtotal_value := subtotal_value + line_total_value;
        END LOOP;
        UPDATE public.quotation_option
        SET subtotal = subtotal_value,
            total = round(subtotal_value + tax_value, 2)
        WHERE id = option_id_value;
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_quotation_v1(
    p_payload JSONB, p_actor_user_id TEXT
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    quotation_row public.quotation%ROWTYPE;
    existing_row public.quotation%ROWTYPE;
    cv public.client_vehicle%ROWTYPE;
    c public.client%ROWTYPE;
    v public.vehicle%ROWTYPE;
    cm public.car_model%ROWTYPE;
    b public.brand%ROWTYPE;
    attended_user public."user"%ROWTYPE;
    attended_person public.person%ROWTYPE;
    external_id_value UUID;
    attended_id TEXT;
BEGIN
    PERFORM public.assert_staff_actor_v1(p_actor_user_id);
    BEGIN external_id_value := (p_payload->>'external_id')::UUID;
    EXCEPTION WHEN OTHERS THEN
        RAISE EXCEPTION 'QUOTATION_EXTERNAL_ID_INVALID' USING ERRCODE = '22023';
    END;
    PERFORM pg_advisory_xact_lock(hashtextextended(external_id_value::TEXT, 0));
    SELECT * INTO existing_row FROM public.quotation
    WHERE external_id = external_id_value FOR UPDATE;
    IF FOUND THEN
        IF existing_row.client_vehicle_id IS DISTINCT FROM
                (p_payload->>'client_vehicle_id')::BIGINT THEN
            RAISE EXCEPTION 'QUOTATION_EXTERNAL_ID_CONFLICT' USING ERRCODE = '23505';
        END IF;
        RETURN public.quotation_public_json_v1(existing_row.id)
            || jsonb_build_object('idempotent_replay', true);
    END IF;
    SELECT * INTO cv FROM public.client_vehicle
    WHERE id = (p_payload->>'client_vehicle_id')::BIGINT AND active = true;
    IF NOT FOUND THEN RAISE EXCEPTION 'CLIENT_VEHICLE_NOT_FOUND' USING ERRCODE = '23503'; END IF;
    SELECT * INTO c FROM public.client WHERE id = cv.client_id AND active = true;
    SELECT * INTO v FROM public.vehicle WHERE id = cv.vehicle_id AND active = true;
    IF c.id IS NULL OR v.id IS NULL THEN
        RAISE EXCEPTION 'CLIENT_VEHICLE_INACTIVE' USING ERRCODE = '23503';
    END IF;
    IF v.car_model_id IS NOT NULL THEN
        SELECT * INTO cm FROM public.car_model WHERE id = v.car_model_id;
        IF cm.brand_id IS NOT NULL THEN SELECT * INTO b FROM public.brand WHERE id = cm.brand_id; END IF;
    END IF;
    attended_id := nullif(btrim(p_payload->>'attended_by_user_id'), '');
    IF attended_id IS NOT NULL THEN
        SELECT * INTO attended_user FROM public."user" WHERE id = attended_id AND active = true;
        IF NOT FOUND THEN RAISE EXCEPTION 'QUOTATION_ATTENDED_BY_NOT_FOUND' USING ERRCODE = '23503'; END IF;
        SELECT * INTO attended_person FROM public.person WHERE id = attended_user.person_id;
    END IF;

    INSERT INTO public.quotation (
        external_id, provisional_reference, folio_number, folio_assigned_at,
        quotation_date, valid_until, client_vehicle_id, client_id, vehicle_id,
        attended_by_user_id, notes, client_snapshot, vehicle_snapshot,
        attended_by_snapshot, legal_text_snapshot, created_by_user_id, updated_by_user_id
    ) VALUES (
        external_id_value,
        coalesce(nullif(btrim(p_payload->>'provisional_reference'), ''),
            'PEND-COT-' || upper(left(external_id_value::TEXT, 8))),
        nextval('public.quotation_folio_number_seq'), now(),
        coalesce((p_payload->>'quotation_date')::DATE, CURRENT_DATE),
        (p_payload->>'valid_until')::DATE,
        cv.id, cv.client_id, cv.vehicle_id, attended_id,
        nullif(btrim(p_payload->>'notes'), ''),
        jsonb_build_object('id', c.id, 'external_id', c.external_id,
            'client_name', c.client_name, 'phone_number', c.phone_number,
            'phone_normalized', c.phone_normalized),
        jsonb_build_object('id', v.id, 'external_id', v.external_id,
            'brand_id', b.id, 'brand_name', b.name, 'car_model_id', cm.id,
            'car_model_name', cm.name, 'model_year', v.model_year,
            'version', v.version, 'color', v.color, 'plate', v.plate),
        CASE WHEN attended_id IS NULL THEN NULL ELSE jsonb_build_object(
            'user_id', attended_user.id, 'person_id', attended_person.id,
            'name', concat_ws(' ', attended_person.name, attended_person.last_name)) END,
        coalesce(p_payload->'legal_text_snapshot', '{}'::JSONB),
        p_actor_user_id, p_actor_user_id
    ) RETURNING * INTO quotation_row;

    PERFORM public.replace_quotation_options_v1(quotation_row.id, p_payload->'options');
    RETURN public.quotation_public_json_v1(quotation_row.id)
        || jsonb_build_object('idempotent_replay', false);
END;
$$;

CREATE OR REPLACE FUNCTION public.update_quotation_v1(
    p_payload JSONB, p_actor_user_id TEXT
