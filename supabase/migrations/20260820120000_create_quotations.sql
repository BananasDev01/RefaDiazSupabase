        CHECK (valid_until IS NULL OR valid_until >= quotation_date),
    CONSTRAINT quotation_accepted_amounts_valid CHECK (
        (accepted_subtotal IS NULL AND accepted_tax_amount IS NULL AND accepted_total IS NULL)
