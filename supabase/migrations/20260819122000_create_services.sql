CREATE OR REPLACE FUNCTION public.touch_service_version_v1()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.external_id IS DISTINCT FROM OLD.external_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.created_by_user_id IS DISTINCT FROM OLD.created_by_user_id THEN
        RAISE EXCEPTION 'Immutable service identity or creation audit fields cannot be changed'
            USING ERRCODE = '22000';
    END IF;

    IF NEW.version IS DISTINCT FROM OLD.version THEN
        RAISE EXCEPTION 'service.version is managed by the database'
            USING ERRCODE = '22000';
    END IF;

    NEW.version := OLD.version + 1;
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.touch_service_version_v1() FROM PUBLIC;

CREATE TRIGGER service_touch_version
BEFORE UPDATE ON public.service
FOR EACH ROW
EXECUTE FUNCTION public.touch_service_version_v1();

