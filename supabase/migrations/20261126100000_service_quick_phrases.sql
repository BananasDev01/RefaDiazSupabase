CREATE FUNCTION public.list_service_quick_phrases_v1(p_field TEXT)
RETURNS JSONB
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
    SELECT coalesce(
        jsonb_agg(
            jsonb_build_object(
                'external_id', q.external_id,
                'phrase', q.phrase,
                'display_order', q.display_order
            )
            ORDER BY q.display_order, q.id
        ),
        '[]'::JSONB
    )
    FROM public.service_quick_phrase q
    WHERE q.field = p_field
      AND q.active;
$$;

-- Reemplaza la lista completa en una sola transacción: edita, reordena,
-- agrega y desactiva las que ya no vienen. Devuelve la lista resultante.
CREATE FUNCTION public.replace_service_quick_phrases_v1(
    p_field TEXT,
    p_phrases JSONB,
    p_actor_user_id TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
    item RECORD;
    item_external_id UUID;
    item_phrase TEXT;
    kept_ids UUID[] := ARRAY[]::UUID[];
BEGIN
    IF p_field IS DISTINCT FROM 'IMPORTANT_INFORMATION' THEN
        RAISE EXCEPTION 'QUICK_PHRASE_FIELD_INVALID' USING ERRCODE = '22023';
    END IF;
    IF p_phrases IS NULL OR jsonb_typeof(p_phrases) <> 'array' OR jsonb_array_length(p_phrases) > 100 THEN
        RAISE EXCEPTION 'QUICK_PHRASE_PAYLOAD_INVALID' USING ERRCODE = '22023';
    END IF;

    -- Serializa ediciones simultáneas de la misma lista.
    PERFORM 1 FROM public.service_quick_phrase WHERE field = p_field FOR UPDATE;

    FOR item IN
        SELECT value, ordinality::INTEGER AS position
        FROM jsonb_array_elements(p_phrases) WITH ORDINALITY
    LOOP
        item_phrase := nullif(btrim(item.value->>'phrase'), '');
        IF item_phrase IS NULL OR char_length(item_phrase) > 500 THEN
            RAISE EXCEPTION 'QUICK_PHRASE_PAYLOAD_INVALID' USING ERRCODE = '22023';
        END IF;
        item_external_id := nullif(item.value->>'external_id', '')::UUID;

        IF item_external_id IS NOT NULL AND EXISTS (
            SELECT 1 FROM public.service_quick_phrase
            WHERE external_id = item_external_id AND field = p_field
        ) THEN
            UPDATE public.service_quick_phrase
            SET phrase = item_phrase,
                display_order = item.position,
                active = true,
                updated_by_user_id = p_actor_user_id,
                updated_at = now()
            WHERE external_id = item_external_id
              AND (phrase, display_order, active) IS DISTINCT FROM (item_phrase, item.position, true);
        ELSE
            INSERT INTO public.service_quick_phrase (
                external_id, field, phrase, display_order, created_by_user_id, updated_by_user_id
            )
            VALUES (
                coalesce(item_external_id, gen_random_uuid()), p_field, item_phrase, item.position,
                p_actor_user_id, p_actor_user_id
            )
            RETURNING external_id INTO item_external_id;
        END IF;

        kept_ids := kept_ids || item_external_id;
    END LOOP;

    UPDATE public.service_quick_phrase
    SET active = false,
        updated_by_user_id = p_actor_user_id,
        updated_at = now()
    WHERE field = p_field
      AND active
      AND NOT (external_id = ANY (kept_ids));

    RETURN public.list_service_quick_phrases_v1(p_field);
END;
$$;

REVOKE ALL ON FUNCTION public.list_service_quick_phrases_v1(TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.replace_service_quick_phrases_v1(TEXT, JSONB, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.list_service_quick_phrases_v1(TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.replace_service_quick_phrases_v1(TEXT, JSONB, TEXT) TO service_role;
