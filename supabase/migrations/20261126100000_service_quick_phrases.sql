-- Frases rápidas compartidas por el equipo para insertar en «Información importante».
CREATE TABLE public.service_quick_phrase (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id UUID NOT NULL DEFAULT gen_random_uuid(),
    field VARCHAR(40) NOT NULL DEFAULT 'IMPORTANT_INFORMATION',
    phrase TEXT NOT NULL,
    display_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    created_by_user_id VARCHAR(500) REFERENCES public."user" (id),
    updated_by_user_id VARCHAR(500) REFERENCES public."user" (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT service_quick_phrase_external_id_unique UNIQUE (external_id),
    CONSTRAINT service_quick_phrase_field_valid CHECK (field IN ('IMPORTANT_INFORMATION')),
    CONSTRAINT service_quick_phrase_phrase_valid CHECK (btrim(phrase) <> '' AND char_length(phrase) <= 500),
    CONSTRAINT service_quick_phrase_display_order_valid CHECK (display_order > 0)
);

CREATE INDEX service_quick_phrase_field_order_idx
    ON public.service_quick_phrase (field, display_order)
    WHERE active;

ALTER TABLE public.service_quick_phrase ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.service_quick_phrase FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.service_quick_phrase TO service_role;

